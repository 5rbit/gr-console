//! Output encodings and the normalized comparison used by `gr-contract gen-link --check`.

/// Start of the header comment of every generated TIA source (`--prune` only removes files carrying it).
pub const GENERATED_MARKER: &str = "// GENERATED by gr-contract gen-link";

pub fn has_generated_marker(text: &str) -> bool {
    text.contains(GENERATED_MARKER)
}

/// TIA source bytes (same as a TIA export): UTF-8 BOM, CRLF line ends, trailing CRLF.
pub(crate) fn tia_bytes(text: &str) -> Vec<u8> {
    let body = text.trim_end_matches(['\r', '\n']);
    let mut out = Vec::with_capacity(body.len() + body.len() / 16 + 5);
    out.extend_from_slice(&[0xEF, 0xBB, 0xBF]);
    for line in body.split('\n') {
        out.extend_from_slice(line.strip_suffix('\r').unwrap_or(line).as_bytes());
        out.extend_from_slice(b"\r\n");
    }
    out
}

/// PC artifact bytes: LF line ends, trailing LF, no BOM.
pub(crate) fn pc_bytes(text: &str) -> Vec<u8> {
    let mut s = text.replace("\r\n", "\n").trim_end_matches('\n').to_string();
    s.push('\n');
    s.into_bytes()
}

/// Comparison form: BOM stripped, CRLF → LF, every run of whitespace collapsed to one space and trimmed, blank
/// lines dropped, ` OF ` compared as ` of `, XML `&apos;` / `&quot;` compared as `'` / `"`. A TIA import + re-export
/// re-indents (`{ S7_Optimized_Access }`, `VAR_*`), widens comment spacing in DB sources (`//   ` → `//    `),
/// upper-cases `Array[*] OF` and writes apostrophes unescaped in tag tables without changing the source.
pub fn normalize_for_compare(bytes: &[u8]) -> String {
    let text = String::from_utf8_lossy(bytes);
    let text: &str = &text;
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut out = String::with_capacity(text.len());
    for line in text.split('\n') {
        let l = line.split_whitespace().collect::<Vec<_>>().join(" ");
        if l.is_empty() {
            continue;
        }
        let l = l.replace(" OF ", " of ").replace("&apos;", "'").replace("&quot;", "\"");
        out.push_str(&canon_numbers(&l));
        out.push('\n');
    }
    out
}

/// Number literal forms of a TIA re-export: `16#A0` → `16#00A0`, `3319752200` → `3_319_752_200`.
/// Hex literals lose `_` and leading zeros and become upper case; `_` between two decimal digits is dropped.
fn canon_numbers(line: &str) -> String {
    let cs: Vec<char> = line.chars().collect();
    let mut out = String::with_capacity(line.len());
    let mut i = 0;
    while i < cs.len() {
        if cs[i] == '1' && cs.get(i + 1) == Some(&'6') && cs.get(i + 2) == Some(&'#') && (i == 0 || !cs[i - 1].is_ascii_alphanumeric()) {
            let mut j = i + 3;
            let mut digits = String::new();
            while j < cs.len() && (cs[j].is_ascii_hexdigit() || cs[j] == '_') {
                if cs[j] != '_' {
                    digits.push(cs[j].to_ascii_uppercase());
                }
                j += 1;
            }
            if !digits.is_empty() {
                let t = digits.trim_start_matches('0');
                out.push_str("16#");
                out.push_str(if t.is_empty() { "0" } else { t });
                i = j;
                continue;
            }
        }
        if cs[i] == '_' && i > 0 && i + 1 < cs.len() && cs[i - 1].is_ascii_digit() && cs[i + 1].is_ascii_digit() {
            i += 1;
            continue;
        }
        out.push(cs[i]);
        i += 1;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn encodings_and_normalization() {
        let t = tia_bytes("A\n  B\n\n");
        assert_eq!(t, b"\xEF\xBB\xBFA\r\n  B\r\n");
        assert_eq!(pc_bytes("x\r\ny"), b"x\ny\n");
        assert_eq!(normalize_for_compare(&t), normalize_for_compare(b"A\n\n\tB   \n"));
        assert_ne!(normalize_for_compare(b"A B"), normalize_for_compare(b"AB"));
        // TIA re-export forms
        assert_eq!(
            normalize_for_compare(b"{ S7_Optimized_Access := 'TRUE' }\r\n   VAR_IN_OUT\r\n      Buf : Array[*] of Byte;   //   x\r\n"),
            normalize_for_compare(b"   { S7_Optimized_Access := 'TRUE' }\nVAR_IN_OUT\n      Buf : Array[*] OF Byte;   //    x")
        );
        assert_eq!(normalize_for_compare(b"<Text>magic &apos;GS&apos;</Text>\n"), normalize_for_compare(b"<Text>magic 'GS'</Text>"));
        assert_ne!(normalize_for_compare(b"Lit := ',\"Use\":'"), normalize_for_compare(b"Lit := ',\"use\":'"));
        assert_eq!(normalize_for_compare(b"A.F := 16#A0; B := 3319752200; C := 16#0000_BEEF;"), normalize_for_compare(b"A.F := 16#00A0; B := 3_319_752_200; C := 16#beef;"));
        assert_ne!(normalize_for_compare(b"B := 16#A0;"), normalize_for_compare(b"B := 16#A1;"));
        assert_eq!(normalize_for_compare("Hello_Bin[0] := 16#0010;   // 한글".as_bytes()), normalize_for_compare("Hello_Bin[0] := 16#10;   // 한글".as_bytes()));
        assert!(has_generated_marker("\t// GENERATED by gr-contract gen-link from \"X\""));
    }
}
